"""Converts the prototype's map generator (Assets/Scripts/Gen/MapGen*.cs, plain C#) into UdonSharp
(Assets/Udon/Scripts/Gen/MapGenUdon*.cs). Run it again whenever the prototype's generator changes:

    python Tools/port_mapgen.py

What it changes, mechanically:
  - class MapGen -> partial class MapGenUdon : UdonSharpBehaviour (one file carries the base class)
  - GenRng (a struct passed by ref) -> uint[1] state arrays and RngRange/RngBetween/RngChance/RngNextU helpers,
    since Udon has no user structs; `ref` in front of an rng argument is dropped (arrays are references)
  - static fields and methods -> instance ones (Udon has no static fields; the tables are instance fields)
  - GenData./GenModels./GenPlans. static fields -> instance fields of the same name, filled in the editor by
    MapGenTableBaker from the plain C# tables (MapGenUdon.Tables.cs, generated here). Constants stay GenData.X.
  - GenData lookups (FindDef, FindGrp, FindTable, IsBuilding, RoomTheme) -> instance methods (MapGenUdon.Lookup.cs)
  - trace output and exceptions removed
The hand-written parts (MapGenUdon.Lookup.cs, MapGenUdon.Rng.cs) are not touched.
"""
import os
import re
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
SRC = os.path.join(ROOT, "Assets", "Scripts", "Gen")
DST = os.path.join(ROOT, "Assets", "Udon", "Scripts", "Gen")
CLS = "MapGenUdon"

TABLE_CLASSES = ["GenData", "GenModels", "GenPlans"]
LOOKUPS = {"FindDef", "FindGrp", "FindTable", "IsBuilding", "RoomTheme", "RoomName"}

HEADER = "// GENERATED by Tools/port_mapgen.py from Assets/Scripts/Gen/{src}. Do not edit: change the prototype and run the tool.\n"


def table_fields():
    """Static non-const fields of the table classes: name -> (class, C# type)."""
    out = {}
    for cls in TABLE_CLASSES:
        text = open(os.path.join(SRC, cls + ".cs"), encoding="utf8").read()
        for m in re.finditer(r"^\s*public\s+static\s+(?:readonly\s+)?([\w\[\]]+)\s+([^;(]+?)\s*(?:;|=\s*(?:new|\{|[-\w\"]))", text, re.M):
            typ = m.group(1)
            if typ in ("class", "void"):
                continue
            # "int[] a = new int[64], b = new int[64]" -> a, b
            decl = m.group(0)
            body = text[m.start():text.index(";", m.start())]
            body = body.split(typ, 1)[1]
            depth = 0
            names, cur = [], ""
            for ch in body:
                if ch in "{([":
                    depth += 1
                elif ch in "})]":
                    depth -= 1
                if ch == "," and depth == 0:
                    names.append(cur)
                    cur = ""
                else:
                    cur += ch
            names.append(cur)
            for n in names:
                n = n.split("=")[0].strip()
                if re.fullmatch(r"\w+", n):
                    out[n] = (cls, typ)
    return out


RECURSIVE = ["Remove", "RemoveOne"]   # found by a call-graph check (WallPlace and StampObject only call their own overloads)
GLOBAL_RNG = {"planR", "layRng"}   # rng fields declared in one file and used in others (MapGenPlace.planR, MapGenSite.layRng)


def convert(text, fields, used):
    # rng variables and parameters
    rng_names = set(re.findall(r"\bGenRng\s+(\w+)", text)) | GLOBAL_RNG

    # trace output: whole statements guarded by TraceRoom, and bare Console lines
    text = re.sub(r"^[ \t]*(?:else\s+)?if\s*\(TraceRoom[^\n]*\n", lambda m: "", text, flags=re.M)
    text = re.sub(r"^[^\n]*System\.Console\.[^\n]*\n", "", text, flags=re.M)
    text = re.sub(r"\bpublic static int TraceRoom = -1;", "int TraceRoom = -1;", text)

    # methods that call themselves (or each other): UdonSharp keeps one set of locals per method unless it is told
    # otherwise, so a nested call overwrote the outer one's (Remove taking back a table left its cells taken: the
    # Udon maps differed from C#)
    for n in RECURSIVE:
        text = re.sub(r"^(\s{4})((?:(?:public|private|static|internal)\s+)*[\w\[\]<>]+\s+" + n + r"\s*\()",
                      lambda m: m.group(1) + "[UdonSharp.RecursiveMethod]" + chr(10) + m.group(1) + m.group(2), text, flags=re.M)

    # class declaration
    text = re.sub(r"\bpublic partial class MapGen\b", "public partial class " + CLS, text)

    # GenRng
    text = re.sub(r"\bref\s+GenRng\s+(\w+)", r"uint[] \1", text)
    text = re.sub(r"\bGenRng\.Sub\(", "RngSub(", text)
    text = re.sub(r"\bGenRng\.Hash32\(", "Hash32(", text)
    text = re.sub(r"\bGenRng\.Mix\(", "Mix(", text)
    text = re.sub(r"\bnew\s+GenRng\(", "RngNew(", text)
    text = re.sub(r"\bGenRng\b", "uint[]", text)
    # a call straight on a new stream: Rng(a, b, c).Range(n) -> RngRange(Rng(a, b, c), n)
    text = re.sub(r"\b(Rng\([^()]*\))\.(Range|Between|Chance)\(", lambda m: "Rng" + m.group(2) + "(" + m.group(1) + ", ", text)
    for n in rng_names:
        text = re.sub(r"\bref\s+" + n + r"\b", n, text)
        text = re.sub(r"\b" + n + r"\.(Range|Between|Chance|NextU)\(\s*", lambda m: "Rng" + m.group(1) + "(" + n + (", " if m.group(1) != "NextU" else ""), text)
    text = text.replace("RngNextU(r)", "RngNextU(r)")

    # table fields and lookups
    def tab(m):
        cls, name = m.group(1), m.group(2)
        if name in LOOKUPS:
            return name
        if name in fields:
            used.add(name)
            return name
        return m.group(0)  # a constant
    text = re.sub(r"\b(GenData|GenModels|GenPlans)\.(\w+)\b", tab, text)

    # statics -> instance (keep const)
    text = re.sub(r"\bpublic static readonly\b", "public", text)
    text = re.sub(r"\bstatic readonly\b", "", text)
    text = re.sub(r"\b(public |private )?static (?!class)", lambda m: (m.group(1) or ""), text)
    text = re.sub(r"\breadonly\s+", "", text)

    # Udon has no remainder for uint: UMod (MapGenUdon.Rng.cs)
    text = re.sub(r"(Hash32\([^;]*?\)) % (\d+)u?\b", r"UMod(\1, \2u)", text)

    # Udon's int -> uint cast is checked (it throws for a negative int); U32 keeps the bits as C# does
    text = u32_casts(text)

    # working arrays sized in the code: never from the scene (an old scene keeps the size it was saved with)
    text = re.sub(r"^(\s*)public (\w+\[\] \w+ = new )", r"\1[System.NonSerialized] public \2", text, flags=re.M)

    # reference equality on strings
    text = text.replace("(object)dnId[i] == (object)id", "dnId[i] == id")

    # exceptions
    text = re.sub(r"throw new System\.Exception\(([^;]*)\);", r"{ UnityEngine.Debug.LogError(\1); }", text)
    return text



def u32_casts(text):
    """(uint)X -> U32(X) for X a name, member access, indexing or a parenthesised expression."""
    out, i = [], 0
    while True:
        j = text.find("(uint)", i)
        if j < 0:
            out.append(text[i:])
            return "".join(out)
        out.append(text[i:j])
        k = j + len("(uint)")
        if k < len(text) and text[k] == "(":
            depth, e = 0, k
            while True:
                if text[e] == "(":
                    depth += 1
                elif text[e] == ")":
                    depth -= 1
                    if depth == 0:
                        break
                e += 1
            out.append("U32" + text[k:e + 1])
            i = e + 1
        else:
            m = re.match(r"[\w.]+(\[[^\]]*\])?", text[k:])
            out.append("U32(" + m.group(0) + ")")
            i = k + m.end()


def main():
    os.makedirs(DST, exist_ok=True)
    fields = table_fields()
    used = set()
    files = sorted(f for f in os.listdir(SRC) if f.startswith("MapGen") and f.endswith(".cs") and f != "MapGenTests.cs")
    for f in files:
        text = open(os.path.join(SRC, f), encoding="utf8").read()
        out = convert(text, fields, used)
        if f == "MapGen.cs":
            out = out.replace("public partial class " + CLS + "\n{",
                              "[UdonSharp.UdonBehaviourSyncMode(UdonSharp.BehaviourSyncMode.None)]\npublic partial class " + CLS + " : UdonSharp.UdonSharpBehaviour\n{", 1)
            # the constructor becomes Init(), called by Begin
            out = re.sub(r"public " + CLS + r"\(\)\s*\{\s*GenData\.Build\(\);\s*", "bool inited;\n\n    void Init()\n    {\n        if (inited) return;\n        inited = true;\n        ", out)
            out = re.sub(r"public MapGen\(\)\s*\{\s*GenData\.Build\(\);\s*", "bool inited;\n\n    void Init()\n    {\n        if (inited) return;\n        inited = true;\n        ", out)
            out = out.replace("seed = seedValue; size = sizeBucket;", "Init();\n        seed = seedValue; size = sizeBucket;", 1)
        part = f[len("MapGen"):-3]
        name = CLS + ("." + part if part else "") + ".cs"   # MapGenUdon.cs carries the class (Unity needs the name)
        open(os.path.join(DST, name), "w", encoding="utf8", newline="\n").write(HEADER.format(src=f) + out)
        print("wrote", name)

    # GenData's lookups over constants (IsBuilding, RoomTheme), copied so they follow the prototype's room and zone lists
    gd = open(os.path.join(SRC, "GenData.cs"), encoding="utf8").read()
    fns = []
    for name in ("IsBuilding", "RoomTheme"):
        m = re.search(r"^    public static (\w+) " + name + r"\(int (\w+)\)", gd, re.M)
        i = m.start()
        line_end = gd.index("\n", i)
        if gd.count("{", i, line_end) == gd.count("}", i, line_end) and "{" in gd[i:line_end]:
            body = gd[i:line_end]                 # a one-liner
        else:
            j = gd.index("\n    }\n", i)         # a block, up to its closing brace
            body = gd[i:j + 6]
        body = body.replace("public static ", "")
        body = re.sub(r"\b((?:Z|R|TH)_\w+)\b", r"GenData.\1", body)
        fns.append(body.rstrip())
    open(os.path.join(DST, CLS + ".DataFns.cs"), "w", encoding="utf8", newline="\n").write(
        HEADER.format(src="GenData.cs (IsBuilding, RoomTheme)") + "public partial class " + CLS + "\n{\n" + "\n\n".join(fns) + "\n}\n")
    print("wrote", CLS + ".DataFns.cs")

    # the tables: instance fields, baked in the editor
    lines = [HEADER.format(src="GenData.cs, GenModels.cs, GenPlans.cs"),
             "// The generator's tables, copied from the plain C# GenData/GenModels/GenPlans by MapGenTableBaker (menu",
             "// PropHunt > Bake map generator tables). Same names as the static fields they come from.",
             "public partial class " + CLS, "{"]
    for n in sorted(used):
        cls, typ = fields[n]
        lines.append("    [UnityEngine.HideInInspector] public %s %s;   // %s" % (typ, n, cls))
    lines.append("}")
    open(os.path.join(DST, CLS + ".Tables.cs"), "w", encoding="utf8", newline="\n").write("\n".join(lines) + "\n")
    print("wrote", CLS + ".Tables.cs", len(used), "fields")


if __name__ == "__main__":
    main()
